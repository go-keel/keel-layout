-- Complete schema of the business database on PostgreSQL: running it on an empty database creates every table at its
-- latest shape. The MySQL version is ../mysql/0_schema.sql; a change goes into both.
-- Rules (directories, 0_schema.sql / 1_baseline.sql / incremental scripts): docs/guides/domain-model.md, "Schema".
-- Table design rules (naming, primary keys, character set, time, indexes): docs/practices/database.md.
-- Every environment (local included) runs it by hand, for example:
--   psql -h 127.0.0.1 -U postgres -d <database> -v ON_ERROR_STOP=1 -f migrations/business/postgres/0_schema.sql

-- Text columns compare ignoring case and accents, as MySQL's utf8mb4_0900_ai_ci does; byte-wise columns leave it off.
CREATE COLLATION IF NOT EXISTS ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

-- Example: delete after forking (through "Example end")
-- todo: to-do items. content is optional; empty string when not given.
CREATE TABLE IF NOT EXISTS todo (
    id         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200)   COLLATE ci NOT NULL,
    content    VARCHAR(2000)  COLLATE ci NOT NULL DEFAULT '',
    completed  BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS todo_idx_completed ON todo (completed);
-- Example end
